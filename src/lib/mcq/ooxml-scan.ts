// ============================================================
// আগে একই ধরনের <w:r>/<w:t> স্ক্যান-regex দুই ফাইলে আলাদা লেখা ছিল:
//   font-remap.ts (RUN_RE/WT_RE) বনাম repack-docx.ts (RUN_SCAN_RE/WT_TEXT_RE)।
// এখন দুই জায়গাই এই মডিউলের কোয়ান্টেড-অ্যাট্রিবিউট-সেফ প্যাটার্ন ব্যবহার করে।
//
// ক্যাপচার-গ্রুপ কনভেনশন (দুটোতেই):
//   RUN_RE:  m[1] = self-closing `/>`-মার্ক, m[2] = ওপেন-রানের ভিতরের XML
//   WT_RE:   m[1] = `/>` অথবা পুরো `>…</w:t>`, m[2] = <w:t>-এর ভিতরের টেক্সট
// সেলফ-ক্লোজিং রান/টেক্সট-এলিমেন্টের কোনো কনটেন্ট নেই — স্ক্যানাররা m[2]/t[2]
// undefined হলে খালি ধরে নেয়।
// ============================================================

/**
 * ওপেন-ট্যাগ-অ্যাট্রিবিউট প্যাটার্ন: স্পেস দিয়ে শুরু হওয়া অ্যাট্রিবিউট-তালিকা,
 * কোটেড ভ্যালুর ভেতরে `>` থাকলেও ধরে (খুব-বিরল কিন্তু নিরাপদ)।
 * `<w:rPr`/`<w:rFonts`-জাতীয় নাম এই প্যাটার্নে ম্যাচ করে না — নামের পরে
 * স্পেস/`>`/`/>` ছাড়া কিছু গ্রহণ করা হয় না।
 */
export const ATTRS_PART = String.raw`(?:(?:\s(?:[^>"']|"[^"]*"|'[^']*')*))?`;

/** <w:r> স্ক্যান: self-closing (`/>`) বা ওপেন…ক্লোজ (রান নেস্ট করে না) — group 2 = রান-বডি */
export const RUN_RE = new RegExp(`<w:r${ATTRS_PART}(/>)|<w:r${ATTRS_PART}>([\\s\\S]*?)</w:r>`, "g");

/** রানের ভেতরে <w:t> স্ক্যান (w:tab/w:instrText ইত্যাদি ম্যাচ করে না) — group 2 = টেক্সট */
export const WT_RE = new RegExp(`<w:t${ATTRS_PART}(/>|>([\\s\\S]*?)</w:t>)`, "g");
